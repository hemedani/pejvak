import coreWebVitals from "eslint-config-next/core-web-vitals";
import tseslint from "typescript-eslint";

/**
 * Flat config, Next 16's own presets plus the three rules this codebase needs to
 * keep its own promises (plan §15).
 *
 * `eslint-config-next/core-web-vitals` already exports a flat config array, so
 * there is no `FlatCompat` wrapper here — one fewer translation layer between the
 * rules that ship with the framework and the ones written for this app.
 *
 * The plugin has to be registered in the *same* config object as the rules that
 * use it. `eslint-config-next` registers `@typescript-eslint` in its own
 * entries, which does not help an object added here: ESLint 9 resolves a rule to
 * the plugins of the object that configures it, and reports "could not find
 * plugin" otherwise. Hence the explicit `plugins` line below rather than relying
 * on the preset's copy.
 */
const config = [
  {
    ignores: [
      ".next/**",
      "node_modules/**",
      "next-env.d.ts",
      // Generated by the backend and vendored byte for byte (plan §2 C6). Linting
      // it would mean either reformatting it — which breaks the drift check — or
      // a permanent list of exceptions.
      "src/types/declarations/**",
    ],
  },

  ...coreWebVitals,

  {
    plugins: { "@typescript-eslint": tseslint.plugin },
    rules: {
      // The plan says "no `any`", so the rule says it too. The one legitimate
      // hole is the generated transport's `req.json()`, and it is closed in
      // `lib/api.ts` rather than tolerated everywhere.
      "@typescript-eslint/no-explicit-any": "error",

      // A `!` is a promise to the compiler that the author cannot always keep.
      // A guard that narrows reads better and cannot be wrong at runtime.
      "@typescript-eslint/no-non-null-assertion": "warn",
    },
  },

  {
    // One icon family, behind one wrapper (plan §7.8). A direct import is how the
    // vocabulary drifted across two families on mobile.
    files: ["src/**/*.{ts,tsx}"],
    rules: {
      "no-restricted-imports": [
        "error",
        {
          paths: [
            {
              name: "lucide-react",
              message: "Use <Icon name=\"…\" /> from @/components/ui/icon.",
            },
          ],
        },
      ],
    },
  },

  {
    files: ["src/components/ui/icon.tsx"],
    rules: { "no-restricted-imports": "off" },
  },

  {
    // Tests index into results that an assertion on the line above already
    // proved exist (`expect(rows).toHaveLength(3); rows[0]!.title`). The `!` is
    // the shortest way to say "the assertion is the proof" — a guard would be
    // three lines of ceremony per assertion, and a guard that throws turns a
    // failing test into an error with no diff.
    files: ["src/**/__tests__/**/*.ts"],
    rules: { "@typescript-eslint/no-non-null-assertion": "off" },
  },
];

export default config;
